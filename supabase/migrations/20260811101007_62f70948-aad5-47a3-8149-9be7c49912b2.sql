-- Uma viagem não pode estar em duas escalas ativas
CREATE OR REPLACE FUNCTION public.check_trip_single_schedule()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.trip_id IS NULL OR NEW.status = 'CANCELADO' THEN
    RETURN NEW;
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.schedule_assignments a
    JOIN public.daily_schedules s ON s.id = a.schedule_id
    WHERE a.trip_id = NEW.trip_id
      AND a.id <> NEW.id
      AND a.schedule_id <> NEW.schedule_id
      AND a.status <> 'CANCELADO'
      AND s.status <> 'CANCELADA'
  ) THEN
    RAISE EXCEPTION 'Esta solicitação já faz parte de outra escala ativa.';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER schedule_assignments_single_schedule
  BEFORE INSERT OR UPDATE ON public.schedule_assignments
  FOR EACH ROW EXECUTE FUNCTION public.check_trip_single_schedule();

-- Conflitos de veículo e motorista em um intervalo
CREATE OR REPLACE FUNCTION public.schedule_conflicts(
  _vehicle_id uuid,
  _driver_id uuid,
  _driver_user_id uuid,
  _start timestamptz,
  _end timestamptz,
  _exclude_assignment uuid DEFAULT NULL
)
RETURNS TABLE (
  kind text,
  assignment_id uuid,
  schedule_id uuid,
  schedule_code integer,
  label text,
  starts_at timestamptz,
  ends_at timestamptz
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT
    CASE
      WHEN _vehicle_id IS NOT NULL AND s.vehicle_id = _vehicle_id THEN 'VEICULO'
      ELSE 'MOTORISTA'
    END AS kind,
    a.id, s.id, s.code,
    COALESCE(NULLIF(a.origin_text,''),'—') || ' → ' || COALESCE(NULLIF(a.destination_text,''),'—'),
    a.scheduled_departure, a.scheduled_arrival
  FROM public.schedule_assignments a
  JOIN public.daily_schedules s ON s.id = a.schedule_id
  WHERE a.status <> 'CANCELADO'
    AND s.status <> 'CANCELADA'
    AND (_exclude_assignment IS NULL OR a.id <> _exclude_assignment)
    AND tstzrange(a.scheduled_departure, a.scheduled_arrival, '[)')
        && tstzrange(_start, _end, '[)')
    AND (
      (_vehicle_id IS NOT NULL AND s.vehicle_id = _vehicle_id)
      OR (_driver_id IS NOT NULL AND s.driver_id = _driver_id)
      OR (_driver_user_id IS NOT NULL AND s.driver_user_id = _driver_user_id)
    )
  ORDER BY a.scheduled_departure;
$$;

-- Próximo horário livre a partir de um instante, mantendo a duração
CREATE OR REPLACE FUNCTION public.suggest_free_slot(
  _vehicle_id uuid,
  _driver_id uuid,
  _driver_user_id uuid,
  _start timestamptz,
  _end timestamptz,
  _exclude_assignment uuid DEFAULT NULL
)
RETURNS timestamptz
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  dur interval := _end - _start;
  cursor_at timestamptz := _start;
  conflict_end timestamptz;
  guard integer := 0;
BEGIN
  LOOP
    guard := guard + 1;
    EXIT WHEN guard > 50;
    SELECT max(c.ends_at) INTO conflict_end
    FROM public.schedule_conflicts(_vehicle_id, _driver_id, _driver_user_id, cursor_at, cursor_at + dur, _exclude_assignment) c;
    IF conflict_end IS NULL THEN
      RETURN cursor_at;
    END IF;
    cursor_at := conflict_end;
  END LOOP;
  RETURN cursor_at;
END $$;

-- Notificação pelo sino existente (admin e motoristas da SRE)
CREATE OR REPLACE FUNCTION public.notify_users(
  _user_ids uuid[],
  _title text,
  _body text,
  _trip_id uuid DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  inserted integer := 0;
BEGIN
  IF NOT (is_admin() OR is_sre_driver(auth.uid())) THEN
    RAISE EXCEPTION 'Sem permissão para notificar usuários.';
  END IF;
  INSERT INTO public.notifications (user_id, title, body, trip_id)
  SELECT DISTINCT u, _title, _body, _trip_id
  FROM unnest(_user_ids) AS u
  WHERE u IS NOT NULL;
  GET DIAGNOSTICS inserted = ROW_COUNT;
  RETURN inserted;
END $$;

