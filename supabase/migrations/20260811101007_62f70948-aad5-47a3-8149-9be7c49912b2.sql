DO $$ BEGIN
  CREATE TYPE public.schedule_status AS ENUM ('RASCUNHO','PLANEJADA','PUBLICADA','EM_EXECUCAO','CONCLUIDA','CANCELADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.assignment_status AS ENUM ('PENDENTE','PROGRAMADO','EM_ANDAMENTO','CONCLUIDO','NAO_REALIZADO','CANCELADO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.segment_type AS ENUM ('LEVAR','BUSCAR','DESLOCAMENTO','AGUARDAR','RETORNO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- HELPERS
CREATE OR REPLACE FUNCTION public.is_sre_driver(_user_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = _user_id AND p.is_sre_driver AND p.is_active)
      OR EXISTS (SELECT 1 FROM public.drivers d WHERE d.profile_id = _user_id AND d.is_active);
$$;

-- TABELAS
CREATE TABLE public.daily_schedules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code integer GENERATED BY DEFAULT AS IDENTITY,
  schedule_date date NOT NULL,
  vehicle_id uuid REFERENCES public.vehicles(id) ON DELETE SET NULL,
  driver_id uuid REFERENCES public.drivers(id) ON DELETE SET NULL,
  driver_user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  status public.schedule_status NOT NULL DEFAULT 'RASCUNHO',
  observations text,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX daily_schedules_date_idx ON public.daily_schedules (schedule_date);
CREATE INDEX daily_schedules_vehicle_idx ON public.daily_schedules (vehicle_id);
CREATE INDEX daily_schedules_driver_idx ON public.daily_schedules (driver_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.daily_schedules TO authenticated;
GRANT ALL ON public.daily_schedules TO service_role;
ALTER TABLE public.daily_schedules ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.schedule_assignments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  schedule_id uuid NOT NULL REFERENCES public.daily_schedules(id) ON DELETE CASCADE,
  trip_id uuid REFERENCES public.trip_requests(id) ON DELETE SET NULL,
  order_index integer NOT NULL DEFAULT 1,
  segment_type public.segment_type NOT NULL DEFAULT 'LEVAR',
  origin_city_id uuid REFERENCES public.cities(id) ON DELETE SET NULL,
  origin_destination_id uuid REFERENCES public.destinations(id) ON DELETE SET NULL,
  origin_text text NOT NULL DEFAULT 'SRE',
  destination_city_id uuid REFERENCES public.cities(id) ON DELETE SET NULL,
  destination_id uuid REFERENCES public.destinations(id) ON DELETE SET NULL,
  destination_text text NOT NULL DEFAULT '',
  requested_at timestamptz,
  scheduled_departure timestamptz NOT NULL,
  scheduled_arrival timestamptz NOT NULL,
  actual_departure timestamptz,
  actual_arrival timestamptz,
  passengers integer NOT NULL DEFAULT 0,
  passengers_names text,
  status public.assignment_status NOT NULL DEFAULT 'PROGRAMADO',
  notes text,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT schedule_assignments_period_check CHECK (scheduled_arrival > scheduled_departure)
);
CREATE INDEX schedule_assignments_schedule_idx ON public.schedule_assignments (schedule_id, order_index);
CREATE INDEX schedule_assignments_trip_idx ON public.schedule_assignments (trip_id);
CREATE INDEX schedule_assignments_dep_idx ON public.schedule_assignments (scheduled_departure);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.schedule_assignments TO authenticated;
GRANT ALL ON public.schedule_assignments TO service_role;
ALTER TABLE public.schedule_assignments ENABLE ROW LEVEL SECURITY;

