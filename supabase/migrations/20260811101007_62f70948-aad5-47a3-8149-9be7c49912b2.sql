-- É o motorista responsável pela escala?
CREATE OR REPLACE FUNCTION public.is_schedule_driver(_schedule_id uuid, _user_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.daily_schedules s
    LEFT JOIN public.drivers d ON d.id = s.driver_id
    WHERE s.id = _schedule_id
      AND (s.driver_user_id = _user_id OR d.profile_id = _user_id OR s.created_by = _user_id)
  );
$$;

-- POLICIES
CREATE POLICY "escalas visiveis" ON public.daily_schedules
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "admin gerencia escalas" ON public.daily_schedules
  FOR ALL TO authenticated USING (is_admin()) WITH CHECK (is_admin());
CREATE POLICY "motorista cria escala" ON public.daily_schedules
  FOR INSERT TO authenticated
  WITH CHECK (is_sre_driver(auth.uid()) AND created_by = auth.uid());
CREATE POLICY "motorista edita propria escala" ON public.daily_schedules
  FOR UPDATE TO authenticated
  USING (is_sre_driver(auth.uid()) AND is_schedule_driver(id, auth.uid()))
  WITH CHECK (is_sre_driver(auth.uid()) AND is_schedule_driver(id, auth.uid()));

CREATE POLICY "atendimentos visiveis" ON public.schedule_assignments
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "admin gerencia atendimentos" ON public.schedule_assignments
  FOR ALL TO authenticated USING (is_admin()) WITH CHECK (is_admin());
CREATE POLICY "motorista gerencia atendimentos da sua escala" ON public.schedule_assignments
  FOR ALL TO authenticated
  USING (is_sre_driver(auth.uid()) AND is_schedule_driver(schedule_id, auth.uid()))
  WITH CHECK (is_sre_driver(auth.uid()) AND is_schedule_driver(schedule_id, auth.uid()));

CREATE POLICY "historico da escala visivel" ON public.schedule_history
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "registra historico da escala" ON public.schedule_history
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());

CREATE POLICY "ocorrencias visiveis" ON public.schedule_incidents
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "admin gerencia ocorrencias" ON public.schedule_incidents
  FOR ALL TO authenticated USING (is_admin()) WITH CHECK (is_admin());
CREATE POLICY "motorista registra ocorrencia" ON public.schedule_incidents
  FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid() AND is_sre_driver(auth.uid()));

